def generate_spec_id(fn_id, case_type, counters):
    code_map = {
        '메인 플로우': 'MAIN',
        '유효성 검증': 'VAL',
        '예외 처리': 'EXC',
        '상태 분기': 'BR',
    }
    code = code_map.get(case_type, 'ETC')
    key = (fn_id, code)
    counters[key] = counters.get(key, 0) + 1
    return f"{fn_id}-{code}-{counters[key]:02d}"

def main():
    wb = openpyxl.load_workbook(WB_PATH)

    # Remove existing spec sheet
    if SPEC_SHEET in wb.sheetnames:
        del wb[SPEC_SHEET]

    ws = wb.create_sheet(SPEC_SHEET)

    # Styles
    header_fill = PatternFill('solid', fgColor='548235')
    header_font = Font(name='Arial', bold=True, color='FFFFFF', size=10)
    body_font = Font(name='Arial', size=9)
    wrap = Alignment(wrap_text=True, vertical='top')
    header_align = Alignment(horizontal='center', vertical='center', wrap_text=True)

    # Title row
    ws.merge_cells('A1:I1')
    title_cell = ws['A1']
    title_cell.value = '베트남 중고차 플랫폼 — 기능명세서 (Feature Specifications)'
    title_cell.font = Font(name='Arial', bold=True, size=12)
    title_cell.alignment = Alignment(horizontal='center', vertical='center')
    ws.row_dimensions[1].height = 24

    # Blank row
    ws.row_dimensions[2].height = 6

    # Header row (row 3)
    headers = ['기능 ID', '스펙 ID', '표시순서', '기능명', '구분', '조건 / 트리거', '처리 내용', '결과 / 화면 반응', '비고']
    col_widths = [15, 28, 10, 22, 12, 35, 55, 55, 15]
    for col_idx, (h, w) in enumerate(zip(headers, col_widths), 1):
        cell = ws.cell(row=3, column=col_idx, value=h)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = header_align
        ws.column_dimensions[get_column_letter(col_idx)].width = w
    ws.row_dimensions[3].height = 20

    # Write data rows
    counters = {}
    display_order = 0
    row_num = 4
    for (fn_id, case_type, condition, process, result, note) in SPECS:
        display_order += 1
        spec_id = generate_spec_id(fn_id, case_type, counters)
        # 기능명 formula references Feature Definitions sheet col D=기능ID, col E=기능명
        fn_name_formula = f"=INDEX('Feature Definitions'!$E:$E,MATCH($A{row_num},'Feature Definitions'!$D:$D,0))"
        row_data = [fn_id, spec_id, display_order, fn_name_formula, case_type, condition, process, result, note]
        for col_idx, val in enumerate(row_data, 1):
            cell = ws.cell(row=row_num, column=col_idx, value=val)
            cell.font = body_font
            cell.alignment = wrap
        ws.row_dimensions[row_num].height = 45
        row_num += 1

    # Freeze panes below header
    ws.freeze_panes = 'A4'

    # Auto filter on header row
    ws.auto_filter.ref = f'A3:{get_column_letter(len(headers))}3'

    wb.save(WB_PATH)
    print(f"Done. Written {row_num - 4} spec rows to '{SPEC_SHEET}' in {WB_PATH}")

    # Summary
    from collections import Counter
    type_counts = Counter(r[1] for r in SPECS)
    print("Breakdown:")
    for k, v in type_counts.items():
        print(f"  {k}: {v}")
    fn_counts = Counter(r[0] for r in SPECS)
    single = [k for k, v in fn_counts.items() if v == 1]
    print(f"Features with only 1 row: {len(single)}")
    if single:
        print(f"  {single}")

if __name__ == '__main__':
    main()
